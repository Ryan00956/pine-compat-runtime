#[test]
fn builtin_signatures_have_runtime_dispatch() {
    let runtime: BTreeSet<_> = RUNTIME_DISPATCHED_CALLS.iter().copied().collect();
    let registered: BTreeSet<_> = pine_builtins::PHASE_1_BUILTINS
        .iter()
        .map(|signature| signature.name)
        .collect();

    let missing_dispatch: Vec<_> = registered
        .iter()
        .copied()
        .filter(|name| !is_declaration_or_input(name))
        .filter(|name| !runtime.contains(name))
        .collect();
    assert!(
        missing_dispatch.is_empty(),
        "registered builtins missing runtime dispatch: {missing_dispatch:?}"
    );

    let unregistered_dispatch: Vec<_> = runtime
        .iter()
        .copied()
        .filter(|name| !is_declaration_or_input(name))
        .filter(|name| !registered.contains(name))
        .collect();
    assert!(
        unregistered_dispatch.is_empty(),
        "runtime dispatch names missing builtin signatures: {unregistered_dispatch:?}"
    );
}

fn is_declaration_or_input(name: &str) -> bool {
    matches!(name, "indicator" | "strategy" | "input") || name.starts_with("input.")
}
